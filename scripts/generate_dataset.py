"""Generate the synthetic Circuit Siege dataset (reproducible).

    python scripts/generate_dataset.py                # default: 4000 games, seed 42
    python scripts/generate_dataset.py --games 500    # quick run

Outputs:
    data/raw/selfplay_games.jsonl          one JSON record per simulated game
    data/processed/positions.csv.gz        one feature row per position (+ label)
    data/processed/positions_sample.csv    first 2000 rows, uncompressed, for inspection
    data/processed/splits.json             train/val/test game ids (split by game)
    reports/data_report.md / .json        data-quality summary
"""

import argparse
import json
import os
import time

import _bootstrap  # noqa: F401

from circuit_siege.training.dataset import generate, make_splits, validate
from circuit_siege.utils import paths


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--games", type=int, default=4000)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--workers", type=int, default=max(1, min(8, (os.cpu_count() or 2) - 1)))
    args = ap.parse_args()

    t0 = time.time()
    print(f"Simulating {args.games} bot-vs-bot games (seed={args.seed}, workers={args.workers}) ...")
    records, df = generate(args.games, seed=args.seed, workers=args.workers)
    print(f"  done in {time.time() - t0:.1f}s -> {len(df):,} positions")

    for p in (paths.RAW_GAMES, paths.POSITIONS, paths.REPORTS_DIR / "x"):
        p.parent.mkdir(parents=True, exist_ok=True)
    with open(paths.RAW_GAMES, "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r) + "\n")
    df.to_csv(paths.POSITIONS, index=False, compression="gzip")
    df.head(2000).to_csv(paths.POSITIONS_SAMPLE, index=False)

    splits = make_splits(df["game_id"].unique(), seed=args.seed)
    splits_meta = {"seed": args.seed, "split_unit": "game_id", **{k: v for k, v in splits.items()}}
    paths.SPLITS.write_text(json.dumps(splits_meta))

    report = validate(df)
    winners = [r["winner"] for r in records]
    first_wins = sum(1 for r in records if r["winner"] == r["first_player"])
    report.update({
        "seed": args.seed,
        "split_games": {k: len(v) for k, v in splits.items()},
        "first_player_win_rate": round(first_wins / len(records), 4),
        "draws": winners.count(0),
        "generation_seconds": round(time.time() - t0, 1),
    })
    (paths.REPORTS_DIR / "data_report.json").write_text(json.dumps(report, indent=2))
    write_markdown(report)
    print(json.dumps({k: v for k, v in report.items() if k != "engineered_feature_stats"}, indent=2))
    print(f"Saved {paths.RAW_GAMES}\n      {paths.POSITIONS}")


def write_markdown(rep: dict):
    lines = [
        "# Data Report", "",
        "Generated by `scripts/generate_dataset.py`. Every number below is computed from the saved dataset.", "",
        f"- Games simulated: **{rep['games']:,}** (seed {rep['seed']})",
        f"- Position rows: **{rep['rows']:,}**, features per row: **{rep['features']}**",
        f"- Missing values: **{rep['missing_values']}**",
        f"- Label balance (1 = perspective player won): {rep['label_balance']}",
        f"- First-player win rate: {rep['first_player_win_rate']:.1%}; draws: {rep['draws']}",
        f"- Split by game: {rep['split_games']}",
        f"- Rows with identical features: {rep['duplicate_feature_rows']:,} "
        f"(of which identical label too: {rep['duplicate_rows_incl_label']:,})", "",
        "Duplicates are kept on purpose. They are almost all early-game positions (for example a",
        "single node on an empty board) that many different games pass through, with different",
        "outcomes. They are real samples of how often each position occurs, and they carry",
        "little information, which is correct for such positions.", "",
        "## Engineered feature statistics", "",
        "| feature | mean | std | min | max |", "|---|---|---|---|---|",
    ]
    for name, s in rep["engineered_feature_stats"].items():
        lines.append(f"| {name} | {s['mean']} | {s['std']} | {s['min']} | {s['max']} |")
    (paths.REPORTS_DIR / "data_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
